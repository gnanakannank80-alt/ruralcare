const i18n = {
  currentLang: localStorage.getItem('ruralcare_lang') || 'en',
  
  languages: [
    { code: 'en', name: 'English', native: 'English' },
    { code: 'hi', name: 'Hindi', native: 'हिन्दी' },
    { code: 'ta', name: 'Tamil', native: 'தமிழ்' },
    { code: 'te', name: 'Telugu', native: 'తెలుగు' },
    { code: 'bn', name: 'Bengali', native: 'বাংলা' },
    { code: 'mr', name: 'Marathi', native: 'मराठी' }
  ],

  t(key, fallback = '') {
    const langDict = translations[this.currentLang] || translations.en;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    return (translations.en && translations.en[key]) || fallback || key;
  },

  setLanguage(langCode) {
    if (translations[langCode]) {
      this.currentLang = langCode;
      localStorage.setItem('ruralcare_lang', langCode);
      document.documentElement.lang = langCode;
      this.applyTranslations();
      window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: langCode } }));
    }
  },

  applyTranslations(container = document) {
    container.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) {
        el.textContent = text;
      }
    });

    container.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.t(key);
      if (text) {
        el.setAttribute('placeholder', text);
      }
    });

    container.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      const text = this.t(key);
      if (text) {
        el.setAttribute('title', text);
      }
    });
  }
};

window.i18n = i18n;
